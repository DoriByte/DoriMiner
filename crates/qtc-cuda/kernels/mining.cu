extern "C" __global__ void __launch_bounds__(QTC_MINING_BLOCK_THREADS, QTC_MIN_BLOCKS) mining_main(u32 *results,
                                       const MiningParams params
                                       ) {
    u32 thread_id = blockIdx.x * blockDim.x + threadIdx.x;
    u32 total_threads = params.dispatch_config[0];
    u32 nonces_per_thread = params.dispatch_config[1];
    u32 total_nonces = params.dispatch_config[2];
    if (thread_id >= total_threads) {
        return;
    }
    u32 base_index = thread_id * nonces_per_thread;
#if QTC_WALK2

    if (base_index >= total_nonces) {
        return;
    }
#endif

    u64 round1[12];
    #pragma unroll
    for (int i = 0; i < 12; i++) {
        round1[i] = ((u64)params.round1[2 * i + 1] << 32) | (u64)params.round1[2 * i];
    }
    u64 lane3 = ((u64)params.lanes[1] << 32) | (u64)params.lanes[0];
    u64 lane7 = ((u64)params.lanes[3] << 32) | (u64)params.lanes[2];
    u32 tgt_hi[8];
    #pragma unroll
    for (int i = 0; i < 8; i++) {
        tgt_hi[i] = params.difficulty_target[8 + i];
    }

#if QTC_WALK2

    u64 v[12];
    walk2_thread_state(round1, lane3, lane7, thread_id, v);
#if QTC_WALK2 == 2

    __shared__ u64 walk_v[256][12];
    #pragma unroll
    for (int i = 0; i < 12; i++) {
        walk_v[threadIdx.x][i] = v[i];
    }
    const volatile u64 *held = walk_v[threadIdx.x];
#endif
#endif
    for (u32 j = 0; j < nonces_per_thread; j++) {
        u32 logical_index = base_index + j;
        if (logical_index >= total_nonces) {
            break;
        }
        u64 first;
#if QTC_WALK2
#if QTC_WALK2 == 2
        #pragma unroll
        for (int i = 0; i < 12; i++) {
            v[i] = held[i];
        }
#endif
        if (!mine_one_walk2(v, params.walk_u[j], tgt_hi, &first)) {
            continue;
        }
#else
        if (!mine_one(round1, lane3, lane7, logical_index, tgt_hi, &first)) {
            continue;
        }
#endif

        u32 slot = atomicAdd(&results[0], 1u);
        if (slot < MAX_HITS) {
            results[1 + slot] = logical_index;
        }
    }
}

