__device__ __forceinline__ u64 reduce128_neg(u32 r0, u32 r1, u32 r2, u32 r3) {
    u32 l, h;
    asm("{\n\t"
        ".reg .u32 t1, t2, p, n;\n\t"
        "sub.cc.u32 t2, %5, %2;\n\t"
        "subc.u32 p, t2, %3;\n\t"
        "add.cc.u32 t1, %3, %4;\n\t"
        "addc.cc.u32 %0, %4, t2;\n\t"
        "not.b32 n, %0;\n\t"
        "addc.u32 %1, p, n;\n\t"
        "}"
        : "=&r"(l), "=&r"(h)
        : "r"(r0), "r"(r1), "r"(r2), "r"(r3));
    return ((u64)h << 32) | (u64)l;
}

__device__ __forceinline__ u64 gf64_mul_negx(u64 a, u64 b) {
    u32 r0, r1, r2, r3;
#if !defined(QTC_HOST) && QTC_MUL_W4
    u32 a0 = (u32)a, a1 = (u32)(a >> 32), b0 = (u32)b, b1 = (u32)(b >> 32);
    asm("{\n\t"
        ".reg .b64 p0, m, m2, p3;\n\t"
        ".reg .b32 m0, m1, p0h, p3l, p3h, cw;\n\t"
        "mul.wide.u32 p0, %4, %6;\n\t"
        "mul.wide.u32 m, %5, %6;\n\t"
        "mul.wide.u32 m2, %4, %7;\n\t"
        "mul.wide.u32 p3, %5, %7;\n\t"
        "mov.b64 {%0, p0h}, p0;\n\t"
        "mov.b64 {p3l, p3h}, p3;\n\t"
        "add.cc.u64 m, m, m2;\n\t"
        "addc.u32 cw, p3h, 0;\n\t"
        "mov.b64 {m0, m1}, m;\n\t"
        "add.cc.u32 %1, p0h, m0;\n\t"
        "addc.cc.u32 %2, p3l, m1;\n\t"
        "addc.u32 %3, cw, 1;\n\t"
        "}"
        : "=&r"(r0), "=&r"(r1), "=&r"(r2), "=&r"(r3)
        : "r"(a0), "r"(a1), "r"(b0), "r"(b1));
#else
    mul64wide(a, b, r0, r1, r2, r3);
    r3 += 1u;
#endif
    return reduce128_neg(r0, r1, r2, r3);
}

__device__ __forceinline__ u64 gf64_sbox_addp_neg(u64 x, u64 c0, u64 c3) {
    u64 x2 = gf64_sqr(x);
    u64 x3 = QTC_MN ? gf64_mul_negx(x2, x) : gf64_mul(x2, x);
    u64 x4 = gf64_sqr(x2);
    u32 r0, r1, r2, r3;
#if !defined(QTC_HOST) && QTC_MUL_W4
    u32 a0 = (u32)x4, a1 = (u32)(x4 >> 32), b0 = (u32)x3, b1 = (u32)(x3 >> 32);
    asm("{\n\t"
        ".reg .b64 p0, m, m2, p3;\n\t"
        ".reg .b32 m0, m1, p0h, p3l, p3h, cw;\n\t"
        "mad.wide.u32 p0, %4, %6, %8;\n\t"
        "mul.wide.u32 m, %5, %6;\n\t"
        "mul.wide.u32 m2, %4, %7;\n\t"
        "mad.wide.u32 p3, %5, %7, %9;\n\t"
        "mov.b64 {%0, p0h}, p0;\n\t"
        "mov.b64 {p3l, p3h}, p3;\n\t"
        "add.cc.u64 m, m, m2;\n\t"
        "addc.u32 cw, p3h, 0;\n\t"
        "mov.b64 {m0, m1}, m;\n\t"
        "add.cc.u32 %1, p0h, m0;\n\t"
        "addc.cc.u32 %2, p3l, m1;\n\t"
        "addc.u32 %3, cw, " QTC_CW_INC ";\n\t"
        "}"
        : "=&r"(r0), "=&r"(r1), "=&r"(r2), "=&r"(r3)
        : "r"(a0), "r"(a1), "r"(b0), "r"(b1), "l"(c0), "l"(c3));
#else
    u64 lo = x4 * x3;
    u64 hi = __umul64hi(x4, x3);
    u64 lo2 = lo + c0;
    hi += ((lo2 < lo) ? 1ULL : 0ULL) + c3;
    r0 = (u32)lo2;
    r1 = (u32)(lo2 >> 32);
    r2 = (u32)hi;
    r3 = (u32)(hi >> 32) + (QTC_MN ? 1u : 0u);
#endif
    return reduce128_neg(r0, r1, r2, r3);
}

__device__ __forceinline__ u64 gf64_sbox_neg(u64 x) {
    u64 x2 = gf64_sqr(x);
    if (QTC_MN) {
        return gf64_mul_negx(gf64_sqr(x2), gf64_mul_negx(x2, x));
    }
    u64 x3 = gf64_mul(x2, x);
    u64 x4 = gf64_sqr(x2);
    u32 r0, r1, r2, r3;
    mul64wide(x4, x3, r0, r1, r2, r3);
    return reduce128_neg(r0, r1, r2, r3);
}

