    u32 k = (u32)(sh >> 32);
    u32 l = (u32)sl - k;
    u32 h = (u32)sh + k - 2u;
    return ((u64)h << 32) | (u64)l;
}

__device__ __forceinline__ u64 gf64_mul(u64 a, u64 b) {
    u32 r0, r1, r2, r3;
    mul64wide(a, b, r0, r1, r2, r3);
    return reduce128(r0, r1, r2, r3);
}

