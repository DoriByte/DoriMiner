__device__ __forceinline__ u64 gf64_sqr_p3(u64 a) {
    u32 a0 = (u32)a, a1 = (u32)(a >> 32);
    u32 r0, r1, r2, r3;
    asm("{\n\t"
        ".reg .b64 p0, m, p3, t;\n\t"
        ".reg .b32 p0h, m0, m1, s, b;\n\t"
        "mul.wide.u32 p0, %4, %4;\n\t"
        "mov.b64 {%0, p0h}, p0;\n\t"
        "shr.u32 s, p0h, 1;\n\t"
        "cvt.u64.u32 t, s;\n\t"
        "mad.wide.u32 m, %4, %5, t;\n\t"
        "mov.b64 {m0, m1}, m;\n\t"
        "and.b32 b, p0h, 1;\n\t"
        "shl.b32 s, m0, 1;\n\t"
        "or.b32 %1, s, b;\n\t"
        "shr.u64 t, m, 31;\n\t"
        "mad.wide.u32 p3, %5, %5, t;\n\t"
        "mov.b64 {%2, %3}, p3;\n\t"
        "}"
        : "=&r"(r0), "=&r"(r1), "=&r"(r2), "=&r"(r3)
        : "r"(a0), "r"(a1));
    return reduce128(r0, r1, r2, r3);
}

__device__ __forceinline__ u64 gf64_sqr_dbl(u64 a) {
    u32 a0 = (u32)a, a1 = (u32)(a >> 32);
    u32 r0, r1, r2, r3;
    asm("{\n\t"
        ".reg .b64 p0, m, p3;\n\t"
        ".reg .b32 d0, a1k, m0, m1, p0h, p3l, p3h;\n\t"
        "add.cc.u32 d0, %4, %4;\n\t"
        "addc.u32 a1k, %5, 0;\n\t"
        "mul.wide.u32 p0, %4, %4;\n\t"
        "mul.wide.u32 m, d0, %5;\n\t"
        "mul.wide.u32 p3, %5, a1k;\n\t"
        "mov.b64 {%0, p0h}, p0;\n\t"
        "mov.b64 {m0, m1}, m;\n\t"
        "mov.b64 {p3l, p3h}, p3;\n\t"
        "add.cc.u32 %1, p0h, m0;\n\t"
        "addc.cc.u32 %2, p3l, m1;\n\t"
        "addc.u32 %3, p3h, 0;\n\t"
        "}"
        : "=&r"(r0), "=&r"(r1), "=&r"(r2), "=&r"(r3)
        : "r"(a0), "r"(a1));
    return reduce128(r0, r1, r2, r3);
}

__device__ __forceinline__ u64 gf64_sqr(u64 a, int sel = 0) {
    if ((QTC_SQR_SITE >> sel) & 1) return gf64_sqr_dbl(a);
#if QTC_SQR_MUL
    return gf64_mul(a, a);
#elif QTC_SQR_DBL
    return gf64_sqr_dbl(a);
#elif !defined(QTC_HOST) && QTC_SQR_ADD
    u32 a0 = (u32)a, a1 = (u32)(a >> 32);
    u32 r0, r1, r2, r3;
    asm("{\n\t"
        ".reg .b64 p0, m, p3;\n\t"
        ".reg .b32 m0, m1, p0h, p3l, p3h;\n\t"
        "mul.wide.u32 p0, %4, %4;\n\t"
        "mul.wide.u32 m, %4, %5;\n\t"
        "mul.wide.u32 p3, %5, %5;\n\t"
        "mov.b64 {%0, p0h}, p0;\n\t"
        "mov.b64 {m0, m1}, m;\n\t"
        "mov.b64 {p3l, p3h}, p3;\n\t"
        "add.cc.u32 %1, p0h, m0;\n\t"
        "addc.cc.u32 %2, p3l, m1;\n\t"
        "addc.u32 %3, p3h, 0;\n\t"
        "add.cc.u32 %1, %1, m0;\n\t"
        "addc.cc.u32 %2, %2, m1;\n\t"
        "addc.u32 %3, %3, 0;\n\t"
        "}"
        : "=&r"(r0), "=&r"(r1), "=&r"(r2), "=&r"(r3)
        : "r"(a0), "r"(a1));
    return reduce128(r0, r1, r2, r3);
#else
    u32 a0 = (u32)a, a1 = (u32)(a >> 32);
    u64 ll = (u64)a0 * a0;
    u64 lh = (u64)a0 * a1;
    u64 hh = (u64)a1 * a1;
    u64 mid = lh << 1;
    u32 mid_top = (u32)(lh >> 63);
    u32 r0 = (u32)ll, r1, r2, r3;
    asm("{\n\t"
        "add.cc.u32 %0, %3, %4;\n\t"
        "addc.cc.u32 %1, %5, %6;\n\t"
        "addc.u32 %2, %7, %8;\n\t"
        "}"
        : "=&r"(r1), "=&r"(r2), "=&r"(r3)
        : "r"((u32)(ll >> 32)), "r"((u32)mid), "r"((u32)hh),
          "r"((u32)(mid >> 32)), "r"((u32)(hh >> 32)), "r"(mid_top));
    return reduce128(r0, r1, r2, r3);
#endif
}

__device__ __forceinline__ u64 gf64_sbox(u64 x, int site = QTC_SITE_EXT) {
    u64 x2 = gf64_sqr(x, site);
    u64 x3 = gf64_mul(x2, x);
    u64 x4 = gf64_sqr(x2, site + 1);
    return gf64_mul(x4, x3);
}

__device__ __forceinline__ u64 gf64_canon(u64 a) {
    return a - ((a >= P64) ? P64 : 0ULL);
}

struct Wide {
    u32 l0;
    u32 l1;
    u32 h;
};

__device__ __forceinline__ Wide wide_from(u64 x) {
    Wide w;
    w.l0 = (u32)x;
    w.l1 = (u32)(x >> 32);
    w.h = 0;
    return w;
}

__device__ __forceinline__ void wide_add(Wide &w, u64 x) {
    u32 x0 = (u32)x, x1 = (u32)(x >> 32);
    asm("{\n\t"
        "add.cc.u32 %0, %0, %3;\n\t"
        "addc.cc.u32 %1, %1, %4;\n\t"
        "addc.u32 %2, %2, 0;\n\t"
        "}"
        : "+r"(w.l0), "+r"(w.l1), "+r"(w.h)
        : "r"(x0), "r"(x1));
}

__device__ __forceinline__ void wide_add_wide(Wide &w, const Wide &x) {
    asm("{\n\t"
        "add.cc.u32 %0, %0, %3;\n\t"
        "addc.cc.u32 %1, %1, %4;\n\t"
        "addc.u32 %2, %2, %5;\n\t"
        "}"
        : "+r"(w.l0), "+r"(w.l1), "+r"(w.h)
        : "r"(x.l0), "r"(x.l1), "r"(x.h));
}

__device__ __forceinline__ u64 wide_reduce_lossy(u32 l0, u32 l1, u32 wh) {
    u32 l, h;
    asm("{\n\t"
        "sub.cc.u32 %0, %2, %4;\n\t"
        "add.u32 %1, %3, %4;\n\t"
        "subc.u32 %1, %1, 0;\n\t"
        "}"
        : "=&r"(l), "=&r"(h)
        : "r"(l0), "r"(l1), "r"(wh));
    return ((u64)h << 32) | (u64)l;
}

__device__ __forceinline__ u64 wide_reduce(const Wide &w, int site = 0) {
    if (QTC_WIDE_LOSSY & site) {
        return wide_reduce_lossy(w.l0, w.l1, w.h);
    }
    u32 l, h;
    asm("{\n\t"
        ".reg .u32 t;\n\t"
        "add.cc.u32 %1, %3, %4;\n\t"
        "addc.u32 t, %4, 0;\n\t"
        "addc.u32 %1, %1, 0;\n\t"
        "sub.cc.u32 %0, %2, t;\n\t"
        "subc.u32 %1, %1, 0;\n\t"
        "}"
        : "=&r"(l), "=&r"(h)
        : "r"(w.l0), "r"(w.l1), "r"(w.h));
    return ((u64)h << 32) | (u64)l;
}

__device__ __forceinline__ void add128_wide(u32 &r0, u32 &r1, u32 &r2,
                                            u32 &r3, const Wide &w) {
    asm("{\n\t"
        "add.cc.u32 %0, %0, %4;\n\t"
        "addc.cc.u32 %1, %1, %5;\n\t"
        "addc.cc.u32 %2, %2, %6;\n\t"
        "addc.u32 %3, %3, 0;\n\t"
        "}"
        : "+r"(r0), "+r"(r1), "+r"(r2), "+r"(r3)
        : "r"(w.l0), "r"(w.l1), "r"(w.h));
}

