#define QTC_P12(k, i) ((k) == 0 ? (i) : (k) == 1 ? 11 - (i) : (k) == 2 ? ((i) * 5) % 12 : (k) == 3 ? ((i) * 7) % 12 : (k) == 4 ? ((i) % 3) * 4 + (i) / 3 : (k) == 5 ? 11 - (((i) % 3) * 4 + (i) / 3) : ((i) + (k)) % 12)

#define QTC_P11(k, i) ((k) == 0 ? (i) : (k) == 1 ? 12 - (i) : (k) == 2 ? (((i) - 1) * 4) % 11 + 1 : (k) == 3 ? (((i) - 1) * 7) % 11 + 1 : (((i) - 1 + (k)) % 11) + 1)

template <typename T>
__device__ __forceinline__ void ext_layer_acc(const T *x, Wide *out) {
    Wide y[12];
    #pragma unroll
    for (int chunk = 0; chunk < 3; chunk++) {
        int o = chunk * 4;
        T x0 = x[o];
        T x1 = x[o + 1];
        T x2 = x[o + 2];
        T x3 = x[o + 3];
        Wide t01 = wide_of(x0);
        wide_acc(t01, x1);
        Wide t23 = wide_of(x2);
        wide_acc(t23, x3);
        Wide t0123 = t01;
        wide_add_wide(t0123, t23);
        Wide t01123 = t0123;
        wide_acc(t01123, x1);
        Wide t01233 = t0123;
        wide_acc(t01233, x3);
        y[o + 3] = t01233;
        wide_acc(y[o + 3], x0);
        wide_acc(y[o + 3], x0);
        y[o + 1] = t01123;
        wide_acc(y[o + 1], x2);
        wide_acc(y[o + 1], x2);
        y[o] = t01123;
        wide_add_wide(y[o], t01);
        y[o + 2] = t01233;
        wide_add_wide(y[o + 2], t23);
    }
    Wide sums[4];
    #pragma unroll
    for (int k = 0; k < 4; k++) {
        sums[k] = y[k];
        wide_add_wide(sums[k], y[k + 4]);
        wide_add_wide(sums[k], y[k + 8]);
    }
    #pragma unroll
    for (int ii = 0; ii < 12; ii++) {
        const int i = QTC_P12(QTC_ORDER_OUT, ii);
        out[i] = y[i];
        wide_add_wide(out[i], sums[i % 4]);
    }
}

__device__ __forceinline__ void ext_layer64(u64 *state, const u64 *rc12, bool with_rc = true) {
    Wide w[12];
    ext_layer_acc(state, w);
    #pragma unroll
    for (int ii = 0; ii < 12; ii++) {
        const int i = QTC_P12(QTC_ORDER_REDUCE, ii);
        if (with_rc) {
            wide_add(w[i], rc12[i]);
        }
        state[i] = wide_reduce(w[i], 1);
    }
}

__device__ __forceinline__ void ext_layer64_seam(u64 *state, bool scaled = false) {
    Wide z[12], w[12];
    ext_layer_acc(state, z);
    ext_layer_acc(z, w);
    #pragma unroll
    for (int i = 0; i < 12; i++) {
        wide_add(w[i], scaled ? (QTC_DIAG_TW == 3 ? (QTC_B5 ? merged_rc_s5_at(i) : QTC_MN ? merged_rc_s4_at(i) : merged_rc_s3_at(i)) : merged_rc_s_at(i)) : merged_rc_at(i));
        state[i] = wide_reduce(w[i], 2);
    }
}

__device__ __forceinline__ u64 ext_layer64_out0(const u64 *state) {
    Wide acc;
    #pragma unroll
    for (int chunk = 0; chunk < 3; chunk++) {
        int o = chunk * 4;
        Wide y = wide_from(state[o]);
        wide_add(y, state[o]);
        wide_add(y, state[o + 1]);
        wide_add(y, state[o + 1]);
        wide_add(y, state[o + 1]);
        wide_add(y, state[o + 2]);
        wide_add(y, state[o + 3]);
        if (chunk == 0) {
            acc = y;
            wide_add_wide(acc, y);
        } else {
            wide_add_wide(acc, y);
        }
    }
    return wide_reduce(acc, 4);
}

