        ".reg .b64 p0, m, m2, p3, t;\n\t"
        ".reg .b32 xh, xc;\n\t"
        "mul.wide.u32 m, %6, %7;\n\t"
        "mul.wide.u32 m2, %5, %8;\n\t"
        "add.cc.u64 m, m, m2;\n\t"
        "addc.u32 xc, 0, 0;\n\t"
