__device__ __forceinline__ void mul128_add_wide(u64 a, u64 b, const Wide &w,
                                                u32 &r0, u32 &r1, u32 &r2,
                                                u32 &r3) {
    u32 a0 = (u32)a, a1 = (u32)(a >> 32), b0 = (u32)b, b1 = (u32)(b >> 32);
#if QTC_FUSED_PAIR
    u64 w0 = w.l0, w1 = ((u64)w.h << 32) | (u64)w.l1;
    asm("{\n\t"
        ".reg .b64 p0, m, m2, p3;\n\t"
        ".reg .b32 m0, m1, p0h, p3l, p3h, cw;\n\t"
        "mad.wide.u32 p0, %4, %6, %8;\n\t"
        "mad.wide.u32 m, %5, %6, %9;\n\t"
        "mul.wide.u32 m2, %4, %7;\n\t"
        "mul.wide.u32 p3, %5, %7;\n\t"
        "mov.b64 {%0, p0h}, p0;\n\t"
        "mov.b64 {p3l, p3h}, p3;\n\t"
        "add.cc.u64 m, m, m2;\n\t"
        "addc.u32 cw, p3h, 0;\n\t"
        "mov.b64 {m0, m1}, m;\n\t"
        "add.cc.u32 %1, p0h, m0;\n\t"
        "addc.cc.u32 %2, p3l, m1;\n\t"
        "addc.u32 %3, cw, 0;\n\t"
        "}"
        : "=&r"(r0), "=&r"(r1), "=&r"(r2), "=&r"(r3)
        : "r"(a0), "r"(a1), "r"(b0), "r"(b1), "l"(w0), "l"(w1));
#else
    u64 w0 = w.l0, w1 = w.l1, w2 = w.h;
    asm("{\n\t"
        ".reg .b64 p0, m, m2, p3;\n\t"
        ".reg .b32 m0, m1, p0h, p3l, p3h, cw;\n\t"
        "mad.wide.u32 p0, %4, %6, %8;\n\t"
        "mad.wide.u32 m, %5, %6, %9;\n\t"
        "mul.wide.u32 m2, %4, %7;\n\t"
        "mad.wide.u32 p3, %5, %7, %10;\n\t"
        "mov.b64 {%0, p0h}, p0;\n\t"
        "mov.b64 {p3l, p3h}, p3;\n\t"
        "add.cc.u64 m, m, m2;\n\t"
        "addc.u32 cw, p3h, 0;\n\t"
        "mov.b64 {m0, m1}, m;\n\t"
        "add.cc.u32 %1, p0h, m0;\n\t"
        "addc.cc.u32 %2, p3l, m1;\n\t"
        "addc.u32 %3, cw, 0;\n\t"
        "}"
        : "=&r"(r0), "=&r"(r1), "=&r"(r2), "=&r"(r3)
        : "r"(a0), "r"(a1), "r"(b0), "r"(b1), "l"(w0), "l"(w1), "l"(w2));
#endif
}

__device__ __forceinline__ void mul128_add_wide_nc(u64 a, u64 b, const Wide &w,
                                                   u32 &r0, u32 &r1, u32 &r2,
                                                   u32 &r3) {
#if defined(QTC_HOST) || (QTC_C_ARITH & 16) || !(QTC_FUSED_PAIR && QTC_FUSED_NC)
    mul128_add_wide(a, b, w, r0, r1, r2, r3);
#else
    u32 a0 = (u32)a, a1 = (u32)(a >> 32), b0 = (u32)b, b1 = (u32)(b >> 32);
    u64 w0 = w.l0, w1 = ((u64)w.h << 32) | (u64)w.l1;
    asm("{\n\t"
        ".reg .b64 p0, m, p3;\n\t"
        ".reg .b32 m0, m1, p0h, p3l, p3h;\n\t"
        "mad.wide.u32 p0, %4, %6, %8;\n\t"
        "mad.wide.u32 m, %5, %6, %9;\n\t"
        "mad.wide.u32 m, %4, %7, m;\n\t"
        "mul.wide.u32 p3, %5, %7;\n\t"
        "mov.b64 {%0, p0h}, p0;\n\t"
        "mov.b64 {p3l, p3h}, p3;\n\t"
        "mov.b64 {m0, m1}, m;\n\t"
        "add.cc.u32 %1, p0h, m0;\n\t"
        "addc.cc.u32 %2, p3l, m1;\n\t"
        "addc.u32 %3, p3h, 0;\n\t"
        "}"
        : "=&r"(r0), "=&r"(r1), "=&r"(r2), "=&r"(r3)
        : "r"(a0), "r"(a1), "r"(b0), "r"(b1), "l"(w0), "l"(w1));
#endif
}

__device__ __forceinline__ u64 gf64_sbox_add(u64 x, u64 c) {
    u64 x2 = gf64_sqr(x);
    u64 x3 = gf64_mul(x2, x);
    u64 x4 = gf64_sqr(x2);
    u32 r0, r1, r2, r3;
    mul128_add_wide(x4, x3, wide_from(c), r0, r1, r2, r3);
    return reduce128(r0, r1, r2, r3);
}

__device__ __forceinline__ u64 gf64_sbox_addp(u64 x, u64 c0, u64 c3, int site = QTC_SITE_EXT) {
    u64 x2 = gf64_sqr(x, site);
    u64 x3 = gf64_mul(x2, x);
    u64 x4 = gf64_sqr(x2, site + 1);
    u32 r0, r1, r2, r3;
#if !defined(QTC_HOST) && QTC_MUL_W4
    u32 a0 = (u32)x4, a1 = (u32)(x4 >> 32), b0 = (u32)x3, b1 = (u32)(x3 >> 32);
    asm("{\n\t"
        ".reg .b64 p0, m, m2, p3;\n\t"
        ".reg .b32 m0, m1, p0h, p3l, p3h, cw;\n\t"
        "mad.wide.u32 p0, %4, %6, %8;\n\t"
        "mul.wide.u32 m, %5, %6;\n\t"
        "mul.wide.u32 m2, %4, %7;\n\t"
        "mad.wide.u32 p3, %5, %7, %9;\n\t"
        "mov.b64 {%0, p0h}, p0;\n\t"
        "mov.b64 {p3l, p3h}, p3;\n\t"
        "add.cc.u64 m, m, m2;\n\t"
        "addc.u32 cw, p3h, 0;\n\t"
        "mov.b64 {m0, m1}, m;\n\t"
        "add.cc.u32 %1, p0h, m0;\n\t"
        "addc.cc.u32 %2, p3l, m1;\n\t"
        "addc.u32 %3, cw, 0;\n\t"
        "}"
        : "=&r"(r0), "=&r"(r1), "=&r"(r2), "=&r"(r3)
        : "r"(a0), "r"(a1), "r"(b0), "r"(b1), "l"(c0), "l"(c3));
#else
    u64 lo = x4 * x3;
    u64 hi = __umul64hi(x4, x3);
    u64 lo2 = lo + c0;
    hi += ((lo2 < lo) ? 1ULL : 0ULL) + c3;
    r0 = (u32)lo2;
    r1 = (u32)(lo2 >> 32);
    r2 = (u32)hi;
    r3 = (u32)(hi >> 32);
#endif
    return reduce128(r0, r1, r2, r3);
}

