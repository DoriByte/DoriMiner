    asm("{\n\t"
        ".reg .u32 t1, t2, p, n;\n\t"
        "add.cc.u32 t2, %3, %6;\n\t"
        "addc.u32 p, %4, %7;\n\t"
        "add.cc.u32 t1, %2, %5;\n\t"
        "addc.cc.u32 %0, t1, t2;\n\t"
        "not.b32 n, t1;\n\t"
        "addc.u32 %1, p, n;\n\t"
        "}"
        : "=&r"(l), "=&r"(h)
        : "r"(y.l0), "r"(y.l1), "r"(y.h), "r"(s.l0), "r"(s.l1), "r"(s.h));
    return ((u64)h << 32) | (u64)l;
}

__device__ __forceinline__ void ext_layer64_s5(u64 *state) {
    Wide y[12];
    #pragma unroll
    for (int chunk = 0; chunk < 3; chunk++) {
        int o = chunk * 4;
        u64 x0 = state[o];
        u64 x1 = state[o + 1];
        u64 x2 = state[o + 2];
        u64 x3 = state[o + 3];
        Wide t01 = wide_of(x0);
        wide_acc(t01, x1);
        Wide t23 = wide_of(x2);
        wide_acc(t23, x3);
        Wide t0123 = t01;
        wide_add_wide(t0123, t23);
        Wide t01123 = t0123;
        wide_acc(t01123, x1);
        Wide t01233 = t0123;
        wide_acc(t01233, x3);
        y[o + 3] = t01233;
        wide_acc(y[o + 3], x0);
        wide_acc(y[o + 3], x0);
        y[o + 1] = t01123;
        wide_acc(y[o + 1], x2);
        wide_acc(y[o + 1], x2);
        y[o] = t01123;
        wide_add_wide(y[o], t01);
        y[o + 2] = t01233;
        wide_add_wide(y[o + 2], t23);
    }
    Wide sums[4];
    #pragma unroll
    for (int k = 0; k < 4; k++) {
        sums[k] = y[k];
        wide_add_wide(sums[k], y[k + 4]);
        wide_add_wide(sums[k], y[k + 8]);
    }
    #pragma unroll
    for (int ii = 0; ii < 12; ii++) {
        const int i = QTC_P12(QTC_ORDER_OUT, ii);
        state[i] = wide_sum_fold5(y[i], sums[i % 4]);
    }
}

__device__ __forceinline__ u64 int_round_p(u64 *state, u64 x, u64 rc0, bool scaled = false) {
    Wide s = wide_from(state[1]);
    #pragma unroll
    for (int i = 2; i < 12; i++) {
        wide_add(s, state[i]);
    }
    wide_add(s, x);
#if QTC_REHOME_RC && QTC_RC0_SBOX

    const Wide &s0 = s;
    (void)rc0;
#else
    Wide s0 = s;
    wide_add(s0, rc0);
#endif
    u32 r0, r1, r2, r3;
#if QTC_FUSED_INT && QTC_DIAG_TW && QTC_REDUCE_ALU
    u64 out0 = (QTC_TW5 && scaled) ? diag_mul_add_tw5(x, 0, s0) : diag_mul_add_tw(x, 0, s0);
    #pragma unroll
    for (int ii = 1; ii < 12; ii++) {
        const int i = QTC_P11(QTC_ORDER_INT, ii);
        state[i] = (QTC_TW5 && scaled) ? diag_mul_add_tw5(state[i], i, s) : diag_mul_add_tw(state[i], i, s);
    }
#elif QTC_FUSED_INT
    mul128_add_wide_nc(x, mds_diag_at(0), s0, r0, r1, r2, r3);
    u64 out0 = reduce128(r0, r1, r2, r3);
    #pragma unroll
    for (int ii = 1; ii < 12; ii++) {
        const int i = QTC_P11(QTC_ORDER_INT, ii);
        if (QTC_NC_LANE(i)) {
            mul128_add_wide_nc(state[i], mds_diag_at(i), s, r0, r1, r2, r3);
        } else {
            mul128_add_wide(state[i], mds_diag_at(i), s, r0, r1, r2, r3);
        }
        state[i] = reduce128(r0, r1, r2, r3);
    }
#else
    mul64wide(x, mds_diag_at(0), r0, r1, r2, r3);
    add128_wide(r0, r1, r2, r3, s0);
    u64 out0 = reduce128(r0, r1, r2, r3);
    #pragma unroll
    for (int i = 1; i < 12; i++) {
        mul64wide(state[i], mds_diag_at(i), r0, r1, r2, r3);
        add128_wide(r0, r1, r2, r3, s);
        state[i] = reduce128(r0, r1, r2, r3);
    }
#endif
    return out0;
}

#ifndef QTC_INT_PIPE
#define QTC_INT_PIPE 0
#endif
#if QTC_INT_PIPE && QTC_FUSED_INT && QTC_DIAG_TW && QTC_REDUCE_ALU && QTC_REHOME_RC && !QTC_RC0_SBOX
#define QTC_INT_PIPE_ON 1
#define QTC_PIPE_LANE(i) state[i] = (QTC_TW5 && scaled) ? diag_mul_add_tw5(state[i], i, s) : QTC_W_PAIRS ? diag_mul_add_tw_w(state[i], i, pw0, pw1) : diag_mul_add_tw(state[i], i, s)
__device__ __forceinline__ u64 int_round_pipe(u64 *state, u64 x, u64 rc0, Wide &s, bool sbox_after, bool scaled = false) {
    wide_add(s, x);
    Wide s0 = s;
    wide_add(s0, rc0);
    u64 t = (QTC_TW5 && scaled) ? diag_mul_add_tw5(x, 0, s0) : diag_mul_add_tw(x, 0, s0);
    u64 x2 = 0, x3 = 0, x4 = 0, out = t;
    u64 pw0 = 0, pw1 = 0;
    if (QTC_W_PAIRS) { wide_as_pairs(s, pw0, pw1); }
#if QTC_INT_PIPE == 1
    if (sbox_after) { x2 = gf64_sqr(t, QTC_SITE_INT); }
#endif
    QTC_PIPE_LANE(1); QTC_PIPE_LANE(2); QTC_PIPE_LANE(3);
    Wide n = wide_from(state[1]);
    wide_add(n, state[2]); wide_add(n, state[3]);
#if QTC_INT_PIPE == 1
    if (sbox_after) { x3 = gf64_mul(x2, t); }
#endif
    QTC_PIPE_LANE(4); QTC_PIPE_LANE(5); QTC_PIPE_LANE(6);
    wide_add(n, state[4]); wide_add(n, state[5]); wide_add(n, state[6]);
#if QTC_INT_PIPE == 1
    if (sbox_after) { x4 = gf64_sqr(x2, QTC_SITE_INT + 1); }
#endif
    QTC_PIPE_LANE(7); QTC_PIPE_LANE(8); QTC_PIPE_LANE(9);
    wide_add(n, state[7]); wide_add(n, state[8]); wide_add(n, state[9]);
#if QTC_INT_PIPE == 1
    if (sbox_after) { out = gf64_mul(x4, x3); }
#endif
    QTC_PIPE_LANE(10); QTC_PIPE_LANE(11);
    wide_add(n, state[10]); wide_add(n, state[11]);
#if QTC_INT_PIPE != 1
    if (sbox_after) { out = gf64_sbox(t, QTC_SITE_INT); }
#endif
    s = n;
    return out;
}
#else
#define QTC_INT_PIPE_ON 0
#endif

__device__ __forceinline__ void ext_round(u64 *state, const u64 *rc12, const u64 *fold12, const u64 *foldp = FOLDP_INITIAL[0], bool scaled = false) {
#if QTC_FOLD_RC == 2
    if (QTC_TW6 && scaled) {
        #pragma unroll
        for (int ii = 0; ii < 12; ii++) {
            const int i = QTC_P12(QTC_ORDER_SBOX, ii);
            state[i] = (QTC_S3_MASK & 2) ? gf64_sbox_addp_neg(state[i], foldp[2 * i], foldp[2 * i + 1])
                                         : gf64_sbox_addp(state[i], foldp[2 * i], foldp[2 * i + 1]);
        }
        if (QTC_S3_MASK & 4) {
            ext_layer64_s5(state);
        } else {
            ext_layer64(state, 0, false);
        }
        return;
    }
    #pragma unroll
    for (int ii = 0; ii < 12; ii++) {
        const int i = QTC_P12(QTC_ORDER_SBOX, ii);
        state[i] = gf64_sbox_addp(state[i], foldp[2 * i], foldp[2 * i + 1]);
    }
    ext_layer64(state, 0, false);
#elif QTC_FOLD_RC
    #pragma unroll
    for (int i = 0; i < 12; i++) {
        state[i] = gf64_sbox_add(state[i], fold12[i]);
    }
    ext_layer64(state, 0, false);
#else
    #pragma unroll
    for (int ii = 0; ii < 12; ii++) {
        const int i = QTC_P12(QTC_ORDER_SBOX, ii);
        state[i] = gf64_sbox(state[i]);
    }
    ext_layer64(state, rc12);
#endif
}

#define LAST_FULL 0
#define LAST_OUT0 1
#define LAST_SEAM 2

#define qtc_cal(x) (x)

__device__ __forceinline__ u64 gf64_sbox_int(u64 x, u64 c0, u64 c3, bool scaled) {
    return (QTC_TW6 && QTC_MN && scaled) ? gf64_sbox_addp_neg(x, c0, c3) : gf64_sbox_addp(x, c0, c3, QTC_SITE_INT);
}

__device__ __forceinline__ void permute64_after_initial_rounds(u64 *state, int last, bool scaled = false, int sp = 0) {
    const bool only_out0 = last == LAST_OUT0;
#if QTC_REHOME_RC && QTC_RC0_SBOX
    const u64 (*kint)[2] = scaled ? (QTC_TW6 ? QTC_T3(KINT)[sp] : KINT_S[sp]) : KINT;
    u64 x = gf64_sbox_int(state[0], kint[0][0], kint[0][1], scaled);
    QTC_PRAGMA(unroll QTC_UNROLL_INT)
    for (int r = 0; r < 21; r++) {
        x = gf64_sbox_int(qtc_cal(int_round_p(state, x, 0ULL, scaled)), kint[r + 1][0], kint[r + 1][1], scaled);
    }
    state[0] = int_round_p(state, x, 0ULL, scaled);
#elif QTC_REHOME_RC && QTC_INT_PIPE_ON
    u64 x = gf64_sbox(state[0], QTC_SITE_INT);
    Wide rs = wide_from(state[1]);
    #pragma unroll
    for (int i = 2; i < 12; i++) {
        wide_add(rs, state[i]);
    }
    QTC_PRAGMA(unroll QTC_UNROLL_INT)
    for (int r = 0; r < 21; r++) {
        x = int_round_pipe(state, x, RC_INTERNAL_R[r + 1], rs, true, scaled);
    }
    state[0] = int_round_pipe(state, x, RC_INTERNAL_R[22], rs, false, scaled);
#elif QTC_REHOME_RC
    u64 x = gf64_sbox(state[0], QTC_SITE_INT);
    QTC_PRAGMA(unroll QTC_UNROLL_INT)
    for (int r = 0; r < 21; r++) {

        x = gf64_sbox(qtc_cal(int_round_p(state, x, RC_INTERNAL_R[r + 1])), QTC_SITE_INT);
    }
    state[0] = int_round_p(state, x, RC_INTERNAL_R[22]);
#else
    u64 x = gf64_sbox(state[0], QTC_SITE_INT);
    QTC_PRAGMA(unroll QTC_UNROLL_INT)
    for (int r = 0; r < 21; r++) {
        x = gf64_sbox(int_round_p(state, x, RC_INTERNAL[r + 1]), QTC_SITE_INT);
    }
    state[0] = int_round_p(state, x, 0ULL);
    #pragma unroll
    for (int i = 0; i < 12; i++) {
        state[i] = gf64_add(state[i], RC_TERMINAL[0][i]);
    }
#endif
    QTC_PRAGMA(unroll QTC_UNROLL_EXT)
    for (int r = 0; r < 3; r++) {
        ext_round(state, RC_TERMINAL[r + 1], FOLD_TERMINAL[r], scaled ? (QTC_TW6 ? QTC_T3(FOLDP_TERMINAL)[sp][r] : FOLDP_TERMINAL_S[sp][r]) : FOLDP_TERMINAL[r], scaled);
    }
    #pragma unroll
    for (int i = 0; i < 12; i++) {
        state[i] = (QTC_TW6 && scaled && (QTC_S3_MASK & 2)) ? gf64_sbox_neg(state[i]) : gf64_sbox(state[i]);
    }
    if (only_out0) {
        state[0] = ext_layer64_out0(state);
    } else if (QTC_MERGE && last == LAST_SEAM) {
        ext_layer64_seam(state, scaled);
    } else {

        ext_layer64(state, 0, false);
    }
}

__device__ __forceinline__ void initial_rounds(u64 *state, int first, bool scaled = false, int sp = 0) {
    QTC_PRAGMA(unroll QTC_UNROLL_EXT)
    for (int r = first; r < 4; r++) {
        const u64 *rc = (QTC_REHOME_RC && r == 3) ? ((QTC_RC0_SBOX) ? RC_INITIAL_R4K : RC_INITIAL_R4) : RC_INITIAL[r + 1];
        ext_round(state, rc, FOLD_INITIAL[r], scaled ? (QTC_TW6 ? QTC_T3(FOLDP_INITIAL)[sp][r] : FOLDP_INITIAL_S[sp][r]) : FOLDP_INITIAL[r], scaled);
    }
}

__device__ __forceinline__ void permute64(u64 *state) {
    ext_layer64(state, RC_INITIAL[0]);
    initial_rounds(state, 0);
    permute64_after_initial_rounds(state, LAST_FULL);
}

__device__ __forceinline__ void finish_two_permutations(u64 *state) {
    QTC_PRAGMA(unroll QTC_UNROLL_PASS)
    for (int pass = 0; pass < 2; pass++) {
        if (pass != 0) {
            ext_round(state, RC_INITIAL[1], FOLD_INITIAL[0], QTC_TW5 ? (QTC_TW6 ? QTC_T3(FOLDP_INITIAL)[pass][0] : FOLDP_INITIAL_S[pass][0]) : FOLDP_INITIAL[0], QTC_TW5);
        }
        initial_rounds(state, 1, QTC_TW5, pass);
        permute64_after_initial_rounds(state, pass != 0 ? LAST_OUT0 : LAST_SEAM, QTC_TW5, pass);
    }
}

__device__ __forceinline__ u32 bswap32(u32 v) {
    return ((v & 0xFFu) << 24) | ((v & 0xFF00u) << 8) | ((v >> 8) & 0xFF00u) |
           (v >> 24);
}

__device__ __forceinline__ void nonce_from_index(const u32 *nonce_base,
                                                 u32 logical_index,
                                                 u32 *current_nonce) {
    u32 val0 = nonce_base[0];
    u32 sum0 = val0 + logical_index;
    current_nonce[0] = sum0;
    u32 carry = (sum0 < val0) ? 1u : 0u;
    #pragma unroll
    for (int i = 1; i < 8; i++) {
        u32 val = nonce_base[i];
        u32 sum = val + carry;
        current_nonce[i] = sum;
        carry = (sum < val) ? 1u : 0u;
    }
    #pragma unroll
    for (int i = 8; i < 16; i++) {
        current_nonce[i] = nonce_base[i];
    }
}

__device__ __forceinline__ void hash_from_midstate(const u64 *mid,
                                                   const u32 *current_nonce,
                                                   u32 *hash_le) {
    u64 st[12];
    #pragma unroll
    for (int i = 0; i < 12; i++) {
        st[i] = mid[i];
    }
    #pragma unroll
    for (int i = 0; i < 8; i++) {
        st[i] = gf64_add(st[i], (u64)bswap32(current_nonce[7 - i]));
    }
    permute64(st);
    st[0] = gf64_add(st[0], 1ULL);
    st[1] = gf64_add(st[1], 1ULL);
    permute64(st);
    u32 first[8];
    #pragma unroll
    for (int i = 0; i < 4; i++) {
        u64 c = gf64_canon(st[i]);
        first[2 * i] = (u32)(c & EPS64);
        first[2 * i + 1] = (u32)(c >> 32);
    }
    #pragma unroll
    for (int i = 0; i < 8; i++) {
        hash_le[15 - i] = bswap32(first[i]);
    }
    permute64(st);
    #pragma unroll
    for (int i = 0; i < 4; i++) {
        u64 c = gf64_canon(st[i]);
        hash_le[7 - 2 * i] = bswap32((u32)(c & EPS64));
        hash_le[6 - 2 * i] = bswap32((u32)(c >> 32));
    }
}

extern "C" __global__ void __launch_bounds__(256, 4) hash_nonces(u32 *hashes, const u32 *midstate,
                                       const u32 *start_nonce, u32 count) {
    u32 tid = blockIdx.x * blockDim.x + threadIdx.x;
    if (tid >= count) {
        return;
    }
    u64 mid[12];
    #pragma unroll
    for (int i = 0; i < 12; i++) {
        mid[i] = ((u64)midstate[2 * i + 1] << 32) | (u64)midstate[2 * i];
    }
    u32 nonce_base[16];
    #pragma unroll
    for (int i = 0; i < 16; i++) {
        nonce_base[i] = start_nonce[i];
    }
    u32 current_nonce[16];
    nonce_from_index(nonce_base, tid, current_nonce);
    u32 hash_le[16];
    hash_from_midstate(mid, current_nonce, hash_le);
    #pragma unroll
    for (int i = 0; i < 16; i++) {
        hashes[tid * 16u + (u32)i] = hash_le[i];
    }
}

__device__ __forceinline__ Wide wide_sum(const Wide &a, const Wide &b) {
    Wide w = a;
    wide_add_wide(w, b);
    return w;
}

__device__ __forceinline__ u64 gf64_sbox_first(u64 x) {
    return (QTC_TW6 && QTC_MN) ? gf64_sbox_neg(x) : gf64_sbox(x);
}

__device__ __forceinline__ u64 sparse_lane(u64 base, const Wide &a, const Wide &b, int site = 8) {
    Wide w = wide_from(base);
    wide_add_wide(w, a);
    wide_add_wide(w, b);
    return wide_reduce(w, site);
}

__device__ __forceinline__ bool mine_from_round1(u64 *st, const u32 *tgt_hi, u64 *first_out) {
    finish_two_permutations(st);
#if QTC_TW6

#if QTC_MN

    if (QTC_FIX_MUL4 != QTC_FIX_MUL5 || QTC_FIX_ADD4 != QTC_FIX_ADD5) {
        st[0] = 0ULL;
    }
    if (QTC_FIX_MUL4 != 1ULL && QTC_FIX_MUL4 != P64 - 1ULL) {
        st[0] = gf64_mul(st[0], QTC_FIX_MUL4);
    }
    if (QTC_FIX_ADD4 != 0ULL) {
        st[0] = gf64_add(st[0], QTC_FIX_ADD4);
    }
#else
    st[0] = gf64_add(QTC_FIX_MUL == 1ULL ? st[0] : gf64_mul(st[0], QTC_FIX_MUL), QTC_FIX_ADD);
#endif
#elif QTC_TW5

    st[0] = gf64_mul_b2(st[0]);
#endif

    u64 c = gf64_canon(st[0]);
#if QTC_TW6 && QTC_MN
    if (QTC_FIX_MUL4 == P64 - 1ULL) {
        c = c ? P64 - c : 0ULL;
    }
#endif
    *first_out = c;
    u32 h_hi = bswap32((u32)(c & EPS64));
    u32 h_lo = bswap32((u32)(c >> 32));
    if (h_hi != tgt_hi[7]) {
        return h_hi < tgt_hi[7];
    }
    return h_lo <= tgt_hi[6];
}

__device__ __forceinline__ bool mine_one(const u64 *round1, u64 lane3, u64 lane7,
                                         u32 index, const u32 *tgt_hi,
                                         u64 *first_out) {

    u64 d = 35ULL * (u64)index;
    u64 y3 = gf64_sbox_first(gf64_add(lane3, d));
    u64 y7 = gf64_sbox_first(gf64_add(lane7, P64 - d));
    Wide a1 = wide_from(y3);
    Wide a2 = wide_sum(a1, a1);
    Wide a3 = wide_sum(a2, a1);
    Wide a4 = wide_sum(a2, a2);
    Wide a6 = wide_sum(a3, a3);
    Wide b1 = wide_from(y7);
    Wide b2 = wide_sum(b1, b1);
    Wide b3 = wide_sum(b2, b1);
    Wide b4 = wide_sum(b2, b2);
    Wide b6 = wide_sum(b3, b3);

    u64 st[12];
    st[0] = sparse_lane(round1[0], a2, b1);
    st[1] = sparse_lane(round1[1], a2, b1);
    st[2] = sparse_lane(round1[2], a6, b3);
    st[3] = sparse_lane(round1[3], a4, b2);
    st[4] = sparse_lane(round1[4], a1, b2);
    st[5] = sparse_lane(round1[5], a1, b2);
    st[6] = sparse_lane(round1[6], a3, b6);
    st[7] = sparse_lane(round1[7], a2, b4);
    st[8] = sparse_lane(round1[8], a1, b1);
    st[9] = sparse_lane(round1[9], a1, b1);
    st[10] = sparse_lane(round1[10], a3, b3);
    st[11] = sparse_lane(round1[11], a2, b2);
    return mine_from_round1(st, tgt_hi, first_out);
}

