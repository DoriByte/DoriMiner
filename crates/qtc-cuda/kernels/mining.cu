__device__ __forceinline__ u64 reduce128(u32 r0, u32 r1, u32 r2, u32 r3) {

    u32 l, h;
    asm("{\n\t"
        ".reg .u32 t, n;\n\t"
        "not.b32 n, %4;\n\t"
        "sub.cc.u32 %0, %2, %4;\n\t"
        "subc.cc.u32 %1, %3, n;\n\t"
        "subc.u32 t, %5, 0xffffffff;\n\t"
        "subc.u32 %1, %1, 1;\n\t"
        "sub.cc.u32 %0, %0, t;\n\t"
        "subc.u32 %1, %1, 0xffffffff;\n\t"
        "}"
        : "=&r"(l), "=&r"(h)
        : "r"(r0), "r"(r1), "r"(r2), "r"(r3));
    return ((u64)h << 32) | (u64)l;
}

