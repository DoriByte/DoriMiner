    st[5] = gf64_add(v[5], u[3]);
    st[6] = gf64_add(v[6], u[4]);
    st[7] = gf64_add(v[7], u[5]);
    st[8] = gf64_add(v[8], u[6]);
    st[9] = gf64_add(v[9], u[6]);
    st[10] = gf64_add(v[10], u[7]);
    st[11] = gf64_add(v[11], u[8]);
    return mine_from_round1(st, tgt_hi, first_out);
}
